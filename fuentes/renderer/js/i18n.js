  let currentLang = 'en';
  const listeners = [];

  function detectSystemLanguage() {
    const sysLang = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
    if (sysLang.startsWith('es')) return 'es';
    if (sysLang.startsWith('pt')) return 'pt-BR';
    if (sysLang.startsWith('fr')) return 'fr';
    if (sysLang.startsWith('it')) return 'it';
    if (sysLang.startsWith('ru')) return 'ru';
    return 'en';
  }

  function init() {
    let savedLang = null;
    try {
      savedLang = localStorage.getItem('diffcore_language');
    } catch (_) {}

    if (!savedLang || !LANGUAGES[savedLang]) {
      savedLang = detectSystemLanguage();
    }
    setLanguage(savedLang, false);
  }

  function getLanguages() {
    return LANGUAGES;
  }

  function getCurrentLanguage() {
    return currentLang;
  }

  function t(key, params) {
    const langDict = TRANSLATIONS[currentLang] || TRANSLATIONS['en'];
    let str = langDict[key];
    if (str === undefined) {
      str = TRANSLATIONS['en'][key] !== undefined ? TRANSLATIONS['en'][key] : key;
    }

    if (params && typeof params === 'object') {
      Object.keys(params).forEach(k => {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), params[k]);
      });
    }
    return str;
  }

  function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (key) {
        el.textContent = t(key);
      }
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (key) {
        el.setAttribute('title', t(key));
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) {
        el.setAttribute('placeholder', t(key));
      }
    });

    // Update active state in language selector UI if present
    const curMeta = LANGUAGES[currentLang] || LANGUAGES['en'];
    const activeLabel = document.getElementById('currentLangLabel');
    if (activeLabel) {
      activeLabel.textContent = `${curMeta.flag} ${curMeta.label}`;
    }
    document.querySelectorAll('.lang-opt').forEach(opt => {
      const clickAttr = opt.getAttribute('onclick') || '';
      if (clickAttr.includes(`'${currentLang}'`)) {
        opt.classList.add('active');
      } else {
        opt.classList.remove('active');
      }
    });

    listeners.forEach(fn => {
      try { fn(currentLang); } catch (e) { console.warn('i18n listener error:', e); }
    });
  }

  function setLanguage(lang, persist = true) {
    if (!LANGUAGES[lang]) {
      lang = 'en';
    }
    currentLang = lang;
    if (persist) {
      try {
        localStorage.setItem('diffcore_language', lang);
      } catch (_) {}
    }
    applyTranslations();
  }

  function onLanguageChange(fn) {
    if (typeof fn === 'function') {
      listeners.push(fn);
    }
  }

  window.i18n = {
    init,
    getLanguages,
    getCurrentLanguage,
    setLanguage,
    t,
    applyTranslations,
    onLanguageChange
  };
